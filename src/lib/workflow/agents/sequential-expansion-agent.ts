/**
 * Create expansion agent with default configuration
 */
export function createExpansionAgent(config?: ExpansionConfig): SequentialExpansionAgent {
    return new SequentialExpansionAgent(config);
}

/**
 * Generate expansions from thread messages
 *
 * Convenience function that extracts context from thread messages
 * and generates expansion questions.
 *
 * @param messages - Thread messages (last message should be from assistant)
 * @param threadTitle - Optional thread title for coherence
 * @param config - Optional expansion configuration
 * @returns Expansion result
 */
export async function generateThreadExpansions(
    messages: ThreadMessage[],
    threadTitle?: string,
    config?: ExpansionConfig
): Promise<ExpansionResult> {
    // Find last assistant message
    const lastAssistantMsg = [...messages].reverse().find(m => m.role === 'assistant');
    const lastUserMsg = [...messages].reverse().find(m => m.role === 'user');

    if (!lastAssistantMsg) {
        throw new ExpansionError(
            'NO_CONTEXT',
            'No assistant message found in thread'
        );
    }

    // Build context
    const context: ExpansionContext = {
        lastMessage: lastAssistantMsg.content,
        lastUserMessage: lastUserMsg?.content,
        threadTitle,
        recentHistory: messages.slice(-6).map(m => ({
            role: m.role,
            content: m.content,
        })),
    };

    // Generate expansions
    const agent = createExpansionAgent(config);
    return agent.generateExpansions(context);
}
