// ============================================================================
// Types
// ============================================================================

/**
 * Expansion question generated by the agent
 */
export interface ExpansionQuestion {
    /** Question text */
    question: string;
    /** Brief explanation of why this question is relevant */
    rationale: string;
    /** Suggested title for the child thread */
    threadTitle: string;
}

/**
 * Result of expansion analysis
 */
export interface ExpansionResult {
    /** Follow-up questions generated */
    questions: ExpansionQuestion[];
    /** Summary of the last message's topic */
    topicSummary: string;
    /** Coherence score (0-1) */
    coherenceScore: number;
}

/**
 * Configuration for expansion generation
 */
export interface ExpansionConfig {
    /** Number of questions to generate (default: 3) */
    questionCount?: number;
    /** Provider ID for AI (default: 'gemini') */
    providerId?: string;
    /** Model to use (default: provider's default) */
    modelId?: string;
    /** Temperature for generation (default: 0.7) */
    temperature?: number;
    /** Maximum tokens for response (default: 1024) */
    maxTokens?: number;
}

/**
 * Context from conversation for expansion
 */
export interface ExpansionContext {
    /** Last message from assistant */
    lastMessage: string;
    /** Last user message (optional, for context) */
    lastUserMessage?: string;
    /** Thread title for coherence */
    threadTitle?: string;
    /** Recent conversation history (last N exchanges) */
    recentHistory?: Array<{ role: string; content: string }>;
}

// ============================================================================
// Errors
// ============================================================================

/**
 * Error codes for expansion agent
 */
export const EXPANSION_ERRORS = {
    NO_API_KEY: 'NO_API_KEY',
    API_ERROR: 'API_ERROR',
    INVALID_RESPONSE: 'INVALID_RESPONSE',
    NO_CONTEXT: 'NO_CONTEXT',
} as const;

/**
 * Custom error class for expansion agent
 */
export class ExpansionError extends Error {
    code: keyof typeof EXPANSION_ERRORS;

    constructor(code: keyof typeof EXPANSION_ERRORS, message: string) {
        super(message);
        this.name = 'ExpansionError';
        this.code = code;
    }
}

