#!/usr/bin/env node
/**
 * Contract Type Generator
 * 
 * Automatically generates TypeScript types from:
 * - Zod schemas
 * - Route loaders
 * - API contracts
 * - Database schemas
 * 
 * This ensures type consistency across the entire codebase.
 */

import { execSync } from 'child_process';
import fs from 'fs/promises';
import path from 'path';
import { glob } from 'glob';

const colors = {
  reset: '\x1b[0m',
  green: '\x1b[32m',
  yellow: '\x1b[33m',
  blue: '\x1b[34m',
  red: '\x1b[31m',
};

function log(message, color = 'reset') {
  console.log(`${colors[color]}${message}${colors.reset}`);
}

// ============================================================================
// Configuration
// ============================================================================

const CONFIG = {
  // Directories to scan for schema definitions
  schemaDirs: [
    'src/domain/**/schemas/*.ts',
    'src/infrastructure/**/schemas/*.ts',
    'src/core/**/schemas/*.ts',
  ],
  
  // Route files to extract loader types from
  routePattern: 'src/routes/**/*.tsx',
  
  // Output directory for generated types
  outputDir: 'src/generated',
  
  // Contract files to sync
  contractFiles: [
    'src/infrastructure/filesystem/platform-contract.ts',
  ],
};

// ============================================================================
// Zod Schema Extractor
// ============================================================================

async function extractZodSchemas(filePath) {
  const content = await fs.readFile(filePath, 'utf-8');
  const schemas = [];
  
  // Match: export const SchemaName = z.object({...})
  const schemaRegex = /export\s+const\s+(\w+)\s*=\s*z\.(object|array|string|number|enum)\(/g;
  let match;
  
  while ((match = schemaRegex.exec(content)) !== null) {
    const [, name, type] = match;
    schemas.push({ name, type, file: filePath });
  }
  
  return schemas;
}

// ============================================================================
// Route Loader Type Extractor
// ============================================================================

async function extractRouteTypes(filePath) {
  const content = await fs.readFile(filePath, 'utf-8');
  const types = [];
  
  // Extract loader return type
  const loaderRegex = /loader:\s*(?:async\s*)?\([^)]*\)\s*(?::\s*([^{]+))?\s*=>/;
  const loaderMatch = content.match(loaderRegex);
  
  if (loaderMatch) {
    types.push({
      kind: 'loader',
      route: path.basename(filePath, '.tsx'),
      returnType: loaderMatch[1]?.trim() || 'unknown',
    });
  }
  
  // Extract params from route path
  const routePathRegex = /createFileRoute\(['"]([^'"]+)['"]\)/;
  const routeMatch = content.match(routePathRegex);
  
  if (routeMatch) {
    const params = routeMatch[1].match(/\$\w+/g) || [];
    types.push({
      kind: 'params',
      route: path.basename(filePath, '.tsx'),
      params: params.map(p => p.replace('$', '')),
    });
  }
  
  return types;
}

// ============================================================================
// Type Definition Generator
// ============================================================================

function generateTypeDefinitions(schemas, routeTypes) {
  const lines = [
    '// AUTO-GENERATED FILE - DO NOT EDIT',
    '// Generated by: pnpm run types:contracts',
    `// Timestamp: ${new Date().toISOString()}`,
    '',
    '// ============================================================================',
    '// Schema Types',
    '// ============================================================================',
    '',
  ];
  
  // Generate types from Zod schemas
  for (const schema of schemas) {
    const typeName = schema.name.replace(/Schema$/, '');
    lines.push(`export type ${typeName} = z.infer<typeof import('${schema.file}').${schema.name}>;`);
  }
  
  lines.push('');
  lines.push('// ============================================================================');
  lines.push('// Route Types');
  lines.push('// ============================================================================');
  lines.push('');
  
  // Generate route parameter types
  const paramTypes = routeTypes.filter(t => t.kind === 'params');
  for (const route of paramTypes) {
    if (route.params.length > 0) {
      lines.push(`export type ${pascalCase(route.route)}Params = {`);
      for (const param of route.params) {
        lines.push(`  ${param}: string;`);
      }
      lines.push(`};`);
      lines.push('');
    }
  }
  
  // Generate loader data types
  const loaderTypes = routeTypes.filter(t => t.kind === 'loader');
  for (const route of loaderTypes) {
    lines.push(`export type ${pascalCase(route.route)}LoaderData = ${route.returnType};`);
  }
  
  return lines.join('\n');
}

function pascalCase(str) {
  return str
    .replace(/[^a-zA-Z0-9]/g, '_')
    .split('_')
    .map(s => s.charAt(0).toUpperCase() + s.slice(1).toLowerCase())
    .join('');
}

// ============================================================================
// Main Execution
// ============================================================================

async function main() {
  log('🔍 Scanning for schemas and contracts...', 'blue');
  
  try {
    // Ensure output directory exists
    await fs.mkdir(CONFIG.outputDir, { recursive: true });
    
    // Extract Zod schemas
    log('  → Extracting Zod schemas...', 'yellow');
    const schemaFiles = await glob(CONFIG.schemaDirs);
    const allSchemas = [];
    
    for (const file of schemaFiles) {
      const schemas = await extractZodSchemas(file);
      allSchemas.push(...schemas);
    }
    
    log(`     Found ${allSchemas.length} schemas`, 'green');
    
    // Extract route types
    log('  → Extracting route types...', 'yellow');
    const routeFiles = await glob(CONFIG.routePattern);
    const allRouteTypes = [];
    
    for (const file of routeFiles) {
      const types = await extractRouteTypes(file);
      allRouteTypes.push(...types);
    }
    
    log(`     Found ${routeFiles.length} routes`, 'green');
    
    // Generate type definitions
    log('  → Generating type definitions...', 'yellow');
    const typeDefinitions = generateTypeDefinitions(allSchemas, allRouteTypes);
    
    // Write generated types
    const outputPath = path.join(CONFIG.outputDir, 'contract-types.ts');
    await fs.writeFile(outputPath, typeDefinitions, 'utf-8');
    
    log(`  ✓ Generated: ${outputPath}`, 'green');
    
    // Generate index file
    const indexContent = [
      '// AUTO-GENERATED FILE - DO NOT EDIT',
      `// Timestamp: ${new Date().toISOString()}`,
      '',
      "export * from './contract-types';",
      '',
    ].join('\n');
    
    await fs.writeFile(path.join(CONFIG.outputDir, 'index.ts'), indexContent, 'utf-8');
    log('  ✓ Generated: index.ts', 'green');
    
    log('\n✅ Contract types generated successfully!', 'green');
    
  } catch (error) {
    log(`\n❌ Error: ${error.message}`, 'red');
    process.exit(1);
  }
}

main();
